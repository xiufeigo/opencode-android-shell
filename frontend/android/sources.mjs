import fs from "node:fs/promises"
import path from "node:path"
import { execFileSync } from "node:child_process"

export async function applyAndroidSources(checkout, here) {
  // Git checkout restores tracked files but keeps files added by our previous
  // patch. Remove only that declared set so repeated builds start from the pin.
  const patches = await Promise.all(
    ["upstream.patch", "sidebar.patch"].map((name) => fs.readFile(path.join(here, name), "utf8")),
  )
  for (const patch of patches) {
    for (const match of patch.matchAll(/^--- \/dev\/null\r?\n\+\+\+ b\/(.+)$/gm)) {
      const filename = path.resolve(checkout, match[1].trim())
      if (!filename.startsWith(path.resolve(checkout) + path.sep)) throw new Error("Patch path escapes build checkout")
      await fs.rm(filename, { force: true })
    }
  }
  for (const name of ["upstream.patch", "sidebar.patch"]) {
    execFileSync("git", ["apply", "--check", path.join(here, name)], { cwd: checkout, stdio: "inherit" })
    execFileSync("git", ["apply", path.join(here, name)], { cwd: checkout, stdio: "inherit" })
  }
  const files = [
    ["platform.ts", "packages/app/src/runtime/platform/android.ts"],
    ["back.ts", "packages/app/src/runtime/platform/android-back.ts"],
    ["menu.ts", "packages/app/src/runtime/platform/android-menu.ts"],
    ["i18n-zh.ts", "packages/app/src/runtime/i18n/zh-android.ts"],
    ["i18n-zht.ts", "packages/app/src/runtime/i18n/zht-android.ts"],
    ["files.mjs", "packages/app/src/runtime/platform/android-files.mjs"],
    ["files.d.mts", "packages/app/src/runtime/platform/android-files.d.mts"],
    ["rpc.mjs", "packages/app/src/runtime/platform/android-rpc.mjs"],
    ["rpc.d.mts", "packages/app/src/runtime/platform/android-rpc.d.mts"],
    ["../embedded-ui/server-state.mjs", "packages/app/src/runtime/platform/android-server-state.mjs"],
    ["../embedded-ui/resize-pointer.mjs", "packages/ui/src/components/android-resize-pointer.mjs"],
    ["../embedded-ui/resize-pointer.d.mts", "packages/ui/src/components/android-resize-pointer.d.mts"],
    ["../terminal/panel-lifecycle.mjs", "packages/gui-plugins/src/terminal/android-handoffs.mjs"],
    ["../terminal/panel-lifecycle.d.mts", "packages/gui-plugins/src/terminal/android-handoffs.d.mts"],
    ["../terminal/session-model.test.ts", "packages/gui-plugins/src/terminal/session-model.test.ts"],
  ]
  // These files were generated by the removed browser adapter in older build checkouts.
  for (const filename of [
    "packages/app/src/runtime/platform/android-browser.tsx",
    "packages/app/src/runtime/platform/android-browser-transport.mjs",
    "packages/app/src/runtime/platform/android-browser-transport.d.mts",
    "packages/app/src/settings/general/android-browser.tsx",
  ]) await fs.rm(path.join(checkout, filename), { force: true })
  await Promise.all(files.map(([from, to]) => fs.copyFile(path.join(here, from), path.join(checkout, to))))
  // 2.2.0 rewrote the GUI SDK; the old Extension-based remote-browser plugin no longer compiles.
  await fs.rm(path.join(checkout, "packages/gui-plugins/src/remote-browser"), { recursive: true, force: true })
  for (const name of ["app", "gui-plugins"]) {
    await fs.writeFile(path.join(checkout, `packages/${name}/tsconfig.android.json`), JSON.stringify({
      extends: "./tsconfig.json", include: ["src", "package.json"], exclude: ["src/**/*.test.ts", "src/**/*.stories.tsx"],
    }, null, 2))
  }
  // Windows Git can check symlinks out as plain text. Resolve the tracked link
  // graph explicitly so type declarations and public images remain real files.
  if (process.platform !== "win32") return
  const links = new Map(execFileSync("git", ["ls-files", "--stage", "-z"], { cwd: checkout, encoding: "utf8" })
    .split("\0").filter(row => row.startsWith("120000 ")).map(row => [row.split("\t")[1], row.split(" ")[1]]))
  const bytes = async name => {
    const hash = links.get(name)
    if (!hash) return fs.readFile(path.join(checkout, name))
    const target = execFileSync("git", ["cat-file", "blob", hash], { cwd: checkout, encoding: "utf8" }).trim()
    return bytes(path.posix.normalize(path.posix.join(path.posix.dirname(name), target)))
  }
  for (const name of links.keys()) {
    if (!name.startsWith("packages/app/")) continue
    await fs.writeFile(path.join(checkout, name), await bytes(name))
  }
}
